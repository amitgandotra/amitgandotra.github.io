// Builds js/data/search-index.js: a lightweight full-text index of every lesson page.
// Run after adding or editing lessons:   node tools/build-search-index.js
// Search still works on titles/blurbs without this file; this adds body-text matching.
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SITE = new Function(fs.readFileSync(path.join(ROOT, "js/data/site.js"), "utf8") + "; return SITE;")();

const strip = (s) =>
  String(s)
    .replace(/<[^>]+>/g, " ")
    .replace(/&(?:[a-z]+|#\d+);/gi, " ")
    .replace(/\s+/g, " ")
    .trim();

function words(code) {
  const seen = new Set();
  (String(code).match(/[A-Za-z_][A-Za-z0-9_]{3,}/g) || []).forEach((w) => seen.add(w.toLowerCase()));
  return [...seen].join(" ");
}

// Interview Q&A (js/data/interview/*.js) is searchable too.
const interview = {};
const iDir = path.join(ROOT, "js/data/interview");
if (fs.existsSync(iDir)) {
  for (const f of fs.readdirSync(iDir).filter((f) => f.endsWith(".js"))) {
    const sandbox = { window: {} };
    new Function("window", fs.readFileSync(path.join(iDir, f), "utf8"))(sandbox.window);
    Object.assign(interview, sandbox.window.INTERVIEW || {});
  }
}

// DSA tips (cues, disguised problems, Python tips) are searchable too.
let tipsText = {};
const tipsFile = path.join(ROOT, "js/data/dsa-tips.js");
if (fs.existsSync(tipsFile)) {
  const w = {};
  new Function("window", fs.readFileSync(tipsFile, "utf8"))(w);
  const T = w.DSA_TIPS;
  for (const [id, p] of Object.entries(T.patterns)) {
    tipsText[`dsa/${id}`] = ["Tips and tricks: spot it, then apply it. Trigger words, disguised problems, Python tips, keywords for this pattern.", p.ask, ...p.cues, ...p.spot.map((x) => x.text + " " + x.why), p.notWhen, p.example.title, ...p.python.map((x) => x.tip)].join(" ");
  }
  tipsText["dsa/playbook"] = [
    "Tips and tricks: pattern recognition, keywords, cheat sheet, pattern finder, drill.",
    ...T.general.steps,
    ...Object.values(T.patterns).flatMap((p) => p.cues),
    ...T.general.constraints.map((r) => r.join(" ")),
    ...(T.general.rules || []).map((r) => r.when + " " + r.think),
    ...(T.general.byShape || []).map((g) => g.shape),
    ...(T.general.byQuestion || []).map((g) => g.ask),
    ...T.general.toolbox.map((x) => x.name + " " + x.use),
    ...T.general.pitfalls.map((x) => x.title),
  ].join(" ");
}

const index = {};
let pages = 0;
for (const t of SITE.topics) {
  for (const s of t.sections) {
    for (const p of s.pages) {
      const file = path.join(ROOT, "topics", t.dir, p.href);
      const html = fs.readFileSync(file, "utf8");
      let prose = "";
      let code = "";
      let practice = "";      // numbered LeetCode problems get their own slot so the length cap cannot cut them off
      const m = html.match(/const PAGE_DATA = ([\s\S]*?);\s*<\/script>/);
      if (m) {
        const d = new Function("return (" + m[1] + ")")();
        const bits = [d.summary, ...(d.keyPoints || d.keyDifferences || d.recognize || []), d.template && d.template.note];
        code += " " + (d.template ? d.template.code : "");
        for (const ex of d.examples || []) {
          bits.push(ex.title, ex.prompt, ex.explanation, ex.complexityWhy);
          code += " " + ex.code;
        }
        bits.push(...(d.gotchas || []), ...(d.practiceExercises || []));
        practice = (d.practiceProblems || []).map((x) => `${x.title} leetcode ${x.n}`).join(" ");
        prose = strip(bits.filter(Boolean).join(" "));
      } else {
        // hand-written page (e.g. Big-O primer): use the visible body text
        const body = html.split('<div class="content">')[1] || "";
        prose = strip(body.split('<section class="quiz-section">')[0].replace(/<pre>[\s\S]*?<\/pre>/g, " "));
      }
      const qa = strip((interview[`${t.id}/${p.id}`] || []).map((x) => x.q + " " + x.a).join(" "));
      const tips = strip((tipsText[`${t.id}/${p.id}`] || "").replace(/\*\*/g, "").replace(/`/g, ""));
      index[`${t.id}/${p.id}`] = (prose.slice(0, 1800) + " " + practice + " " + tips.slice(0, 1500) + " " + qa.slice(0, 1500) + " " + words(code).slice(0, 500)).trim();
      pages++;
    }
  }
}

const out = "// Generated by tools/build-search-index.js. Do not edit by hand.\nwindow.SEARCH_INDEX = " + JSON.stringify(index) + ";\n";
fs.writeFileSync(path.join(ROOT, "js/data/search-index.js"), out);
console.log(`indexed ${pages} pages, ${(out.length / 1024).toFixed(0)} KB`);
